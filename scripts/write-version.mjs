// Writes src/version.ts so Settings can show which build you are looking at (web and Android app share one code).
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
let commit = 'dev';
try { commit = execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim() || 'dev'; } catch { /* not a git checkout */ }
writeFileSync('src/version.ts', `// Generated by scripts/write-version.mjs. Do not edit.\nexport const APP_VERSION = '${pkg.version}';\nexport const APP_COMMIT = '${commit}';\n`);
console.log(`version ${pkg.version} (${commit})`);
