// Turns scanner diagnostics captures (IMEI-Lens/diag lines, masked numbers only) into a replay fixture for the JVM grouping tests.
// The fixture keeps only geometry: line boxes, text length, digit counts. Every masked number becomes a synthetic 15-digit number with a
// deliberately WRONG checksum (equal masked numbers stay equal), so no real IMEI and no checksum-valid number enters the repository.
//   node scripts/make-geometry-fixture.mjs <out.txt> <prefix>:<diag.jsonl>:<truth.json> [...]
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const luhnOk = s => { let t = 0; for (let i = 0; i < 15; i++) { let d = +s[14 - i]; if (i % 2 === 1) { d *= 2; if (d > 9) d -= 9; } t += d; } return t % 10 === 0; };
const synthetic = masked => {
  const h = createHash('sha256').update('geometry-fixture:' + masked).digest();
  let s = '99'; for (let i = 0; s.length < 15; i++) s += String(h[i] % 10);
  if (luhnOk(s)) s = s.slice(0, 14) + String((+s[14] + 1) % 10); // never checksum-valid
  return s;
};
const digits = (n, seed) => { let s = ''; for (let i = 0; i < n; i++) s += String((seed + i * 7) % 10); return s; };
const mask = d => `${d.slice(0, 8)}***${d.slice(-4)}`;

const out = ['# Replay fixture for LabelGeometry (generated by scripts/make-geometry-fixture.mjs). Geometry from real scans; numbers are synthetic and checksum-invalid.',
  '# photo <id> <width> <height> <real labels> <groups on the device, -1 when a tile pass ran> <Auto target> <Model lines> <barcode labels>',
  '# i1 <left> <top> <right> <bottom> <text>       (an "IMEI 1" line as read)',
  '# a <kind> <left> <top> <right> <bottom> <len>  (landmark lines: model, imei2, sn)'];
for (const spec of process.argv.slice(3)) {
  const [prefix, diagFile, truthFile] = spec.split(':');
  const truth = JSON.parse(readFileSync(truthFile, 'utf8'));
  const names = Object.keys(truth);
  for (const line of readFileSync(diagFile, 'utf8').split('\n').filter(Boolean)) {
    const d = JSON.parse(line);
    const name = d.photo.replace(/^REAL-/, '');
    const index = names.indexOf(name);
    if (index < 0) continue;
    const number = (name.match(/multi-(\d+)/) || [])[1] || String(index + 1).padStart(2, '0');
    // capture-time results: groups after the first read (no tile pass ran when tilePasses is 0), Auto target
    out.push(`photo ${prefix}-${number} ${d.w} ${d.h} ${truth[name].labels} ${d.tilePasses ? -1 : d.groups} ${d.target} ${d.modelLines} ${d.barcodeLabels}`);
    for (const h of d.imeiOneLines) {
      const numberDigits = Math.max(0, (h.d ?? 16) - 1); // the "1" of "IMEI 1" is counted in d
      let body;
      if (h.n && /\*\*\*/.test(h.n)) body = synthetic(h.n);
      else if (numberDigits === 15) body = digits(8, h.b[0]) + '.' + digits(7, h.b[1]); // 15 digits that do not form one number
      else body = digits(numberDigits, h.b[0]);
      let text = 'IMEI 1:' + body;
      while (text.length < (h.len ?? text.length)) text += 'x';
      out.push(`i1 ${h.b.join(' ')} ${text}`);
    }
    const a = d.anchors || {};
    for (const kind of ['model', 'imei2', 'sn']) for (const b of a[kind] || []) out.push(`a ${kind} ${b.slice(0, 5).join(' ')}`);
  }
}
const text = out.join('\n') + '\n';
if (/\d{15}/.test(text) && [...text.matchAll(/(?<!\d)\d{15}(?!\d)/g)].some(m => luhnOk(m[0]))) throw new Error('a checksum-valid number slipped into the fixture');
writeFileSync(process.argv[2], text);
console.log(`wrote ${process.argv[2]}: ${out.filter(l => l.startsWith('photo')).length} photos`);
